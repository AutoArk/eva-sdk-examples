#!/usr/bin/env node

import { readFile, rm, writeFile } from "node:fs/promises";
import { isAbsolute, resolve } from "node:path";
import { fileURLToPath, pathToFileURL } from "node:url";

const demoRoot = resolve(fileURLToPath(new URL("..", import.meta.url)));
const overridePath = resolve(demoRoot, "pubspec_overrides.yaml");

export function assertLocalSdk(localSdkPath, pubspecContents) {
  if (!isAbsolute(localSdkPath)) {
    throw new Error("local SDK path must be absolute and point to the SDK repository's flutter directory");
  }
  if (!/^name:\s*autoark_eva_client_sdk\s*$/m.test(pubspecContents)) {
    throw new Error("local SDK pubspec must declare name: autoark_eva_client_sdk");
  }
}

export function createOverride(localSdkPath) {
  return [
    "# Generated by scripts/use-local-sdk.mjs; intentionally ignored by Git.",
    "dependency_overrides:",
    "  autoark_eva_client_sdk:",
    `    path: ${JSON.stringify(localSdkPath)}`,
    "",
  ].join("\n");
}

export async function main(args = process.argv.slice(2)) {
  const [selection, ...extra] = args;
  if (selection === undefined || extra.length > 0) {
    throw new Error("usage: node scripts/use-local-sdk.mjs <absolute-sdk-flutter-path|--registry>");
  }

  if (selection === "--registry") {
    await rm(overridePath, { force: true });
    console.log("Registry mode restored. Run flutter pub get to resolve the committed pub.dev dependency.");
    return;
  }

  const localSdkPath = resolve(selection);
  if (!isAbsolute(selection)) {
    throw new Error("local SDK path must be absolute and point to the SDK repository's flutter directory");
  }
  const pubspecContents = await readFile(resolve(localSdkPath, "pubspec.yaml"), "utf8");
  assertLocalSdk(localSdkPath, pubspecContents);
  await writeFile(overridePath, createOverride(localSdkPath), { encoding: "utf8", mode: 0o600 });
  console.log(`Local SDK override enabled for ${localSdkPath}. Run flutter pub get.`);
}

const entryPath = process.argv[1];
if (entryPath !== undefined && import.meta.url === pathToFileURL(resolve(entryPath)).href) {
  try {
    await main();
  } catch (error) {
    const message = error instanceof Error ? error.message : String(error);
    console.error("Local SDK switch failed: " + message);
    process.exitCode = 1;
  }
}
